"""Builds lithopt-domains.js: calibration-domain summaries from datasets published by the calibration authors.
Author: Kishan Tiwari <kishantiwari@iitkgp.ac.in>

Only summary statistics (mean vector, precision matrix, percentiles of D2) are written; the experiments
themselves are not redistributed. Also writes validation/_experiments.json (git-ignored) for the scripts
in paper/, which evaluate LithoPT against the same authors' independent test data.

Usage: python validation/make_domains.py <folder containing 5968_Appendix1.xlsx>
Source: Neave & Putirka (2017), Am. Mineral. 102, 777-794, Appendix 1 (deposit item AM-17-45968).
"""
import json, os, sys
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else "."
LAMBDA = 0.05  # shrinkage of the covariance towards its diagonal
LIQ = ["SiO2", "TiO2", "Al2O3", "FeOt", "MnO", "MgO", "CaO", "Na2O", "K2O", "Cr2O3", "P2O5", "H2O"]
CPX = ["SiO2", "TiO2", "Al2O3", "FeOt", "MnO", "MgO", "CaO", "Na2O", "K2O", "Cr2O3"]
# variables that define the domain: major oxides of both phases (minor, often unreported oxides are left out)
FEATURES = [f"Liq_{o}" for o in LIQ[:9]] + [f"Cpx_{o}" for o in ["SiO2", "TiO2", "Al2O3", "FeOt", "MgO", "CaO", "Na2O"]]


def read(sheet):
    df = pd.read_excel(os.path.join(SRC, "5968_Appendix1.xlsx"), sheet_name=sheet, header=None)
    rows = []
    for r in range(6, df.shape[0]):
        v = df.iloc[r]
        try:
            P, T = float(v[3]), float(v[4])
        except (TypeError, ValueError):
            continue
        num = lambda x: 0.0 if pd.isna(x) else float(x)
        liq = {o: num(v[5 + i]) for i, o in enumerate(LIQ)}
        cpx = {o: num(v[18 + i]) for i, o in enumerate(CPX)}
        if np.isfinite(P) and np.isfinite(T) and liq["SiO2"] > 0 and cpx["SiO2"] > 0:
            rows.append({"ref": str(v[0]), "P_kbar": P, "T_C": T, "Liq": liq, "Cpx": cpx})
    return rows


def matrix(rows):
    return np.array([[r[f.split("_")[0]][f.split("_")[1]] for f in FEATURES] for r in rows])


cal, glob, thol = read("Calibration data"), read("Global test data"), read("Tholeiite test data")
X = matrix(cal)
mu, S = X.mean(axis=0), np.cov(X, rowvar=False)
S = (1 - LAMBDA) * S + LAMBDA * np.diag(np.diag(S))
prec = np.linalg.inv(S)
d2 = np.einsum("ij,jk,ik->i", X - mu, prec, X - mu)
domains = {"NeavePutirka2017": {
    "label": "Neave & Putirka (2017) calibration experiments", "n": int(len(cal)), "equations": ["P_Neave2017"], "features": FEATURES,
    "mean": [round(float(v), 6) for v in mu], "precision": [[float(f"{v:.6g}") for v in row] for row in prec],
    "d2_p95": round(float(np.percentile(d2, 95)), 3), "d2_p99": round(float(np.percentile(d2, 99)), 3)}}

js = ("// Calibration-domain summaries generated by validation/make_domains.py. Do not edit.\n"
      "// Summary statistics only; see that script for the published source of each dataset.\n"
      "(function (root, d) { if (typeof module === \"object\" && module.exports) module.exports = d; else root.LithoPT_DOMAINS = d; })"
      "(typeof self !== \"undefined\" ? self : this, " + json.dumps(domains, separators=(",", ":")) + ");\n")
open(os.path.join(HERE, "..", "lithopt-domains.js"), "w", encoding="utf8", newline="\n").write(js)
json.dump({"calibration": cal, "global_test": glob, "tholeiite_test": thol}, open(os.path.join(HERE, "_experiments.json"), "w"))
print(f"calibration n={len(cal)}, global test n={len(glob)}, tholeiite test n={len(thol)}; D2 p95={domains['NeavePutirka2017']['d2_p95']}, p99={domains['NeavePutirka2017']['d2_p99']}")
